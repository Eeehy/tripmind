// Longest name wins: “西湖曲院风荷” must not resolve to the broad “西湖” alias.
export function findAttractions(text, preferredCity) {
  return ATTRACTIONS.map(item => ({ item, length: Math.max(0, ...[item.name, ...item.aliases].filter(name => text.includes(name)).map(name => name.length)) }))
    .filter(match => match.length > 0)
    .sort((a, b) => b.length - a.length || Number(b.item.city === preferredCity) - Number(a.item.city === preferredCity))
    .map(match => match.item);
}
